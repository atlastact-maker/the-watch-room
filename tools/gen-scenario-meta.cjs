#!/usr/bin/env node
// Regenerates src/lib/sim/scenarios/meta.ts — the light index of every
// scenario (id, title, type, patch, severity, trigger, location, the
// premises notes the records search shows, and the attendance) that the
// desk lists jobs from without downloading their bodies.
//
//   npm run scenarios:meta             rewrite meta.ts from the modules
//   node tools/sim-check/run.cjs meta  fails while meta.ts is stale
//
// No downloads, bundles or application server: the scenario modules are
// required through the same TypeScript transpile hook as the sim checks.
/* eslint-disable @typescript-eslint/no-require-imports -- a CommonJS script, like tools/sim-check/run.cjs */
const fs = require("node:fs");
const path = require("node:path");
const Module = require("node:module");

const root = path.resolve(__dirname, "..");
const SCENARIO_DIR = path.join(root, "src/lib/sim/scenarios");
const META_PATH = path.join(SCENARIO_DIR, "meta.ts");

function installTsRequire() {
  if (require.extensions[".ts"]) return;
  const ts = require("typescript");
  const resolve = Module._resolveFilename;
  Module._resolveFilename = function (request, ...args) {
    return resolve.call(this, request.startsWith("@/") ? path.join(root, "src", request.slice(2)) : request, ...args);
  };
  require.extensions[".ts"] = function (module, filename) {
    const { outputText } = ts.transpileModule(fs.readFileSync(filename, "utf8"), {
      compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true },
      fileName: filename,
    });
    module._compile(outputText, filename);
  };
}

/** The scenario module files, in registry order: NN_slug.ts. */
function scenarioFiles() {
  return fs
    .readdirSync(SCENARIO_DIR)
    .filter((f) => /^\d\d_.*\.ts$/.test(f))
    .sort();
}

/** Every scenario body, read from its own module rather than index.ts so
 *  the generator runs before meta.ts exists (index.ts re-exports it). */
function readScenarios() {
  installTsRequire();
  return scenarioFiles().map((file) => {
    const mod = require(path.join(SCENARIO_DIR, file));
    const key = Object.keys(mod).find((k) => /^scenario\d+$/.test(k));
    if (!key) throw new Error(`${file}: no scenarioNN export`);
    const sc = mod[key];
    if (sc.id !== file.slice(0, 2)) throw new Error(`${file}: id "${sc.id}" does not match the file name`);
    return sc;
  });
}

/** The ScenarioMeta projection of one scenario. Keep in step with the
 *  ScenarioMeta type in src/lib/sim/incident_types.ts. */
function projectMeta(sc) {
  return {
    id: sc.id,
    slug: sc.slug,
    title: sc.title,
    type: sc.type,
    patch: sc.patch,
    severity: sc.severity,
    trigger: sc.trigger,
    location: {
      address: sc.location.address,
      postcode: sc.location.postcode,
      coords: { lat: sc.location.coords.lat, lng: sc.location.coords.lng },
    },
    property: {
      class: sc.property.class,
      firstDueStationId: sc.property.firstDueStationId,
      knownHazards: [...sc.property.knownHazards],
      vulnerabilities: [...sc.property.vulnerabilities],
    },
    pri: { items: [...sc.pri.items] },
    pda: sc.pda.map((slot) => {
      const out = {
        id: slot.id,
        label: slot.label,
        service: slot.service,
        requiredApplianceTypes: [...slot.requiredApplianceTypes],
        requiredCapabilities: [...slot.requiredCapabilities],
      };
      if (slot.preferredStationId !== undefined) out.preferredStationId = slot.preferredStationId;
      if (slot.notes !== undefined) out.notes = slot.notes;
      return out;
    }),
  };
}

/** The full text of meta.ts for the modules as they stand. */
function renderScenarioMeta() {
  const rows = readScenarios().map(projectMeta);
  return (
    "// GENERATED by tools/gen-scenario-meta.cjs — do not edit by hand.\n" +
    "// Regenerate with `npm run scenarios:meta` after adding or changing a\n" +
    "// scenario; `node tools/sim-check/run.cjs meta` fails while it is stale.\n" +
    "//\n" +
    "// The light face of every scenario: what the menus, the county board,\n" +
    "// the call generator, the standard-attendance fallback and the records\n" +
    "// search read without the call script, informant script, scene or\n" +
    "// records. The body arrives on demand through loadScenario(id).\n" +
    'import type { ScenarioMeta } from "../incident_types";\n\n' +
    `export const SCENARIO_META: ScenarioMeta[] = ${JSON.stringify(rows, null, 2)};\n`
  );
}

module.exports = { META_PATH, SCENARIO_DIR, scenarioFiles, readScenarios, projectMeta, renderScenarioMeta };

if (require.main === module) {
  const text = renderScenarioMeta();
  const before = fs.existsSync(META_PATH) ? fs.readFileSync(META_PATH, "utf8") : null;
  if (before === text) {
    console.log(`${path.relative(root, META_PATH)} is up to date.`);
  } else {
    fs.writeFileSync(META_PATH, text);
    console.log(`Wrote ${path.relative(root, META_PATH)} (${text.length} bytes).`);
  }
}
